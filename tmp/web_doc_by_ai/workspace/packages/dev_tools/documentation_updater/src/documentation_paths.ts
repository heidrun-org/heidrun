/**
 * The paths and the texts that the documentation updater uses. Every path is relative to the root folder of the
 * Git repository.
 */
export class DocumentationPaths {
	/** The folder of the documentation pages. */
	static readonly documentationFolder = 'packages/auxiliary/website_public/docs/documentation';

	/** The file that holds the last documented commit. */
	static readonly lastDocumentedCommitFile = `${DocumentationPaths.documentationFolder}/.last_documented_commit`;

	/** The VitePress configuration, which holds the sidebar. */
	static readonly sidebarConfigFile = 'packages/auxiliary/website_public/docs/.vitepress/config.ts';

	/** The folder of the rule files of the user interface. */
	static readonly rulesFolder = 'docs/agents_rules/user_interface';

	/** The glossary. */
	static readonly glossaryFile = 'docs/agents_rules/glossary.md';

	/** The folders of the application, where a user-facing change happens. */
	static readonly applicationFolders = ['packages/apps'];

	/** The name of the page that the script `pnpm docs:shortcuts` generates. The coding agent never edits it. */
	static readonly shortcutsPageName = 'shortcuts.md';

	/** The mark on the first lines of every page that the coding agent owns. */
	static readonly generatedMark = '<!-- generated by docs:update_by_ai -->';

	/** The pattern of the comment on the line after the mark, which names the page type of the Diátaxis framework. */
	static readonly pageTypeCommentPattern = /<!--\s*page type:\s*(\S+?)\s*-->/;

	/** The pattern of the comment under a heading of level two, which names the rule file of the section. */
	static readonly sourceCommentPattern = /<!--\s*source:\s*(\S+?)\s*-->/g;
}
